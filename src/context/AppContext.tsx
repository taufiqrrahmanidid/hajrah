import React, { createContext, useContext, useState, useEffect } from 'react';
import { 
  Tenant, 
  TravelPackage, 
  Jamaah, 
  Booking, 
  PaymentRecord, 
  ChartOfAccount, 
  JournalEntry, 
  InventoryItem, 
  Lead, 
  BroadcastLog, 
  Agent, 
  RoleType,
  TenantBranding,
  TenantModules
} from '../types';
import { 
  INITIAL_TENANTS, 
  INITIAL_PACKAGES, 
  INITIAL_JAMAAH, 
  INITIAL_BOOKINGS, 
  INITIAL_PAYMENTS, 
  INITIAL_COA, 
  INITIAL_JOURNALS, 
  INITIAL_INVENTORY, 
  INITIAL_LEADS, 
  INITIAL_BROADCASTS, 
  INITIAL_AGENTS 
} from '../mock/initialData';

interface AppContextType {
  // Tenancy & RBAC
  tenants: Tenant[];
  currentTenant: Tenant;
  setCurrentTenantId: (id: string) => void;
  currentUserRole: RoleType;
  setCurrentUserRole: (role: RoleType) => void;
  currentView: string;
  setCurrentView: (view: string) => void;

  // Tenant Admin Actions
  createTenant: (tenantData: Partial<Tenant>) => void;
  updateTenantBranding: (tenantId: string, branding: Partial<TenantBranding>) => void;
  toggleTenantModule: (tenantId: string, moduleKey: keyof TenantModules) => void;

  // Domain Entities
  packages: TravelPackage[];
  jamaahList: Jamaah[];
  bookings: Booking[];
  payments: PaymentRecord[];
  coaList: ChartOfAccount[];
  journals: JournalEntry[];
  inventory: InventoryItem[];
  leads: Lead[];
  broadcasts: BroadcastLog[];
  agents: Agent[];

  // Entity Handlers
  addPackage: (pkg: Omit<TravelPackage, 'id' | 'tenantId' | 'bookedSeats'>) => void;
  addJamaah: (jamaah: Omit<Jamaah, 'id' | 'tenantId'>, bookingDetails: { roomType: 'Quad' | 'Triple' | 'Double'; dpAmount?: number; paymentMethod?: any }) => void;
  updateJamaahDocStatus: (jamaahId: string, docKey: keyof Jamaah['documents'], status: any) => void;
  addPayment: (payment: Omit<PaymentRecord, 'id' | 'tenantId' | 'receiptNumber'>) => void;
  addJournalEntry: (entry: Omit<JournalEntry, 'id' | 'tenantId' | 'referenceNo' | 'isAutoGenerated'>) => void;
  updateInventoryStock: (itemId: string, warehouse: 'stockPusat' | 'stockBandara' | 'stockCabang', delta: number) => void;
  addLead: (lead: Omit<Lead, 'id' | 'tenantId' | 'updatedAt'>) => void;
  updateLeadStage: (leadId: string, newStage: Lead['stage']) => void;
  sendBroadcast: (broadcast: Omit<BroadcastLog, 'id' | 'tenantId' | 'sentAt' | 'status'>) => void;
  payoutAgentCommission: (agentId: string, amount: number) => void;
  // Theme (Dark & Light)
  theme: 'light' | 'dark';
  setTheme: (theme: 'light' | 'dark') => void;
  toggleTheme: () => void;

  // Helpers
  formatIdr: (amount: number) => string;
}

const AppContext = createContext<AppContextType | undefined>(undefined);

export const AppProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [tenants, setTenants] = useState<Tenant[]>(() => {
    const saved = localStorage.getItem('hajrah_tenants');
    return saved ? JSON.parse(saved) : INITIAL_TENANTS;
  });

  const [currentTenantId, setCurrentTenantIdState] = useState<string>(() => {
    return localStorage.getItem('hajrah_current_tenant_id') || 'tenant-almabrur';
  });

  const [currentUserRole, setCurrentUserRoleState] = useState<RoleType>(() => {
    return (localStorage.getItem('hajrah_user_role') as RoleType) || 'owner';
  });

  const [currentView, setCurrentViewState] = useState<string>('dashboard');

  const [theme, setThemeState] = useState<'light' | 'dark'>(() => {
    const saved = localStorage.getItem('hajrah_theme');
    return (saved === 'light' || saved === 'dark') ? saved : 'dark';
  });

  useEffect(() => {
    localStorage.setItem('hajrah_theme', theme);
    if (theme === 'dark') {
      document.documentElement.classList.add('dark');
    } else {
      document.documentElement.classList.remove('dark');
    }
  }, [theme]);

  const toggleTheme = () => {
    setThemeState(prev => (prev === 'dark' ? 'light' : 'dark'));
  };

  const setTheme = (newTheme: 'light' | 'dark') => {
    setThemeState(newTheme);
  };

  const [packages, setPackages] = useState<TravelPackage[]>(() => {
    const saved = localStorage.getItem('hajrah_packages');
    return saved ? JSON.parse(saved) : INITIAL_PACKAGES;
  });

  const [jamaahList, setJamaahList] = useState<Jamaah[]>(() => {
    const saved = localStorage.getItem('hajrah_jamaah');
    return saved ? JSON.parse(saved) : INITIAL_JAMAAH;
  });

  const [bookings, setBookings] = useState<Booking[]>(() => {
    const saved = localStorage.getItem('hajrah_bookings');
    return saved ? JSON.parse(saved) : INITIAL_BOOKINGS;
  });

  const [payments, setPayments] = useState<PaymentRecord[]>(() => {
    const saved = localStorage.getItem('hajrah_payments');
    return saved ? JSON.parse(saved) : INITIAL_PAYMENTS;
  });

  const [coaList, setCoaList] = useState<ChartOfAccount[]>(() => {
    const saved = localStorage.getItem('hajrah_coa');
    return saved ? JSON.parse(saved) : INITIAL_COA;
  });

  const [journals, setJournals] = useState<JournalEntry[]>(() => {
    const saved = localStorage.getItem('hajrah_journals');
    return saved ? JSON.parse(saved) : INITIAL_JOURNALS;
  });

  const [inventory, setInventory] = useState<InventoryItem[]>(() => {
    const saved = localStorage.getItem('hajrah_inventory');
    return saved ? JSON.parse(saved) : INITIAL_INVENTORY;
  });

  const [leads, setLeads] = useState<Lead[]>(() => {
    const saved = localStorage.getItem('hajrah_leads');
    return saved ? JSON.parse(saved) : INITIAL_LEADS;
  });

  const [broadcasts, setBroadcasts] = useState<BroadcastLog[]>(() => {
    const saved = localStorage.getItem('hajrah_broadcasts');
    return saved ? JSON.parse(saved) : INITIAL_BROADCASTS;
  });

  const [agents, setAgents] = useState<Agent[]>(() => {
    const saved = localStorage.getItem('hajrah_agents');
    return saved ? JSON.parse(saved) : INITIAL_AGENTS;
  });

  // Save changes to localStorage
  useEffect(() => {
    localStorage.setItem('hajrah_tenants', JSON.stringify(tenants));
  }, [tenants]);

  useEffect(() => {
    localStorage.setItem('hajrah_packages', JSON.stringify(packages));
  }, [packages]);

  useEffect(() => {
    localStorage.setItem('hajrah_jamaah', JSON.stringify(jamaahList));
  }, [jamaahList]);

  useEffect(() => {
    localStorage.setItem('hajrah_bookings', JSON.stringify(bookings));
  }, [bookings]);

  useEffect(() => {
    localStorage.setItem('hajrah_payments', JSON.stringify(payments));
  }, [payments]);

  useEffect(() => {
    localStorage.setItem('hajrah_journals', JSON.stringify(journals));
  }, [journals]);

  useEffect(() => {
    localStorage.setItem('hajrah_inventory', JSON.stringify(inventory));
  }, [inventory]);

  useEffect(() => {
    localStorage.setItem('hajrah_leads', JSON.stringify(leads));
  }, [leads]);

  useEffect(() => {
    localStorage.setItem('hajrah_broadcasts', JSON.stringify(broadcasts));
  }, [broadcasts]);

  useEffect(() => {
    localStorage.setItem('hajrah_agents', JSON.stringify(agents));
  }, [agents]);

  const currentTenant = tenants.find(t => t.id === currentTenantId) || tenants[0];

  const setCurrentTenantId = (id: string) => {
    setCurrentTenantIdState(id);
    localStorage.setItem('hajrah_current_tenant_id', id);
  };

  const setCurrentUserRole = (role: RoleType) => {
    setCurrentUserRoleState(role);
    localStorage.setItem('hajrah_user_role', role);
    if (role === 'super_admin') {
      setCurrentViewState('super_admin');
    } else if (role === 'jamaah') {
      setCurrentViewState('public_b2c');
    } else if (currentView === 'super_admin') {
      setCurrentViewState('dashboard');
    }
  };

  const setCurrentView = (view: string) => {
    setCurrentViewState(view);
  };

  const formatIdr = (amount: number) => {
    return new Intl.NumberFormat('id-ID', {
      style: 'currency',
      currency: 'IDR',
      maximumFractionDigits: 0
    }).format(amount);
  };

  // Actions
  const createTenant = (tenantData: Partial<Tenant>) => {
    const newId = `tenant-${Date.now().toString(36)}`;
    const newTenant: Tenant = {
      id: newId,
      code: (tenantData.code || 'TRAVEL').toUpperCase(),
      name: tenantData.name || 'New Travel Agency',
      companyName: tenantData.companyName || `PT ${tenantData.name} Wisata`,
      subdomain: tenantData.subdomain || 'travel',
      plan: tenantData.plan || 'Pro',
      status: 'active',
      createdAt: new Date().toISOString().split('T')[0],
      expiresAt: '2027-12-31',
      maxJamaahQuota: tenantData.plan === 'Enterprise' ? 2000 : tenantData.plan === 'Pro' ? 800 : 300,
      currentJamaahCount: 0,
      branding: {
        primaryColor: tenantData.branding?.primaryColor || '#059669',
        secondaryColor: tenantData.branding?.secondaryColor || '#10b981',
        logoText: tenantData.name || 'Travel Umrah',
        tagline: tenantData.branding?.tagline || 'Melayani Jamaah dengan Amanah dan Khidmat',
        ppiuNumber: tenantData.branding?.ppiuNumber || 'PPIU Kemenag RI Pending',
        address: tenantData.branding?.address || 'Jakarta, Indonesia',
        phone: tenantData.branding?.phone || '+62 812 0000 0000',
        email: tenantData.branding?.email || 'admin@travel.com',
        domain: tenantData.branding?.domain || `${tenantData.subdomain || 'travel'}.com`
      },
      modules: {
        packages: true,
        jamaah: true,
        payments: true,
        accounting: true,
        inventory: true,
        crmBroadcast: true,
        agency: true,
        dms: true,
        iso9001: true
      }
    };
    setTenants(prev => [...prev, newTenant]);
    setCurrentTenantId(newId);
  };

  const updateTenantBranding = (tenantId: string, branding: Partial<TenantBranding>) => {
    setTenants(prev => prev.map(t => {
      if (t.id === tenantId) {
        return {
          ...t,
          branding: { ...t.branding, ...branding }
        };
      }
      return t;
    }));
  };

  const toggleTenantModule = (tenantId: string, moduleKey: keyof TenantModules) => {
    setTenants(prev => prev.map(t => {
      if (t.id === tenantId) {
        return {
          ...t,
          modules: {
            ...t.modules,
            [moduleKey]: !t.modules[moduleKey]
          }
        };
      }
      return t;
    }));
  };

  const addPackage = (pkg: Omit<TravelPackage, 'id' | 'tenantId' | 'bookedSeats'>) => {
    const newPkg: TravelPackage = {
      ...pkg,
      id: `pkg-${Date.now().toString(36)}`,
      tenantId: currentTenant.id,
      bookedSeats: 0
    };
    setPackages(prev => [newPkg, ...prev]);
  };

  const addJamaah = (
    jamaahData: Omit<Jamaah, 'id' | 'tenantId'>, 
    bookingDetails: { roomType: 'Quad' | 'Triple' | 'Double'; dpAmount?: number; paymentMethod?: any }
  ) => {
    const newJamId = `jam-${Date.now().toString(36)}`;
    const bookingCode = `BK-${currentTenant.code}-${Math.floor(100000 + Math.random() * 900000)}`;

    const newJamaah: Jamaah = {
      ...jamaahData,
      id: newJamId,
      tenantId: currentTenant.id,
      bookingCode,
      status: bookingDetails.dpAmount && bookingDetails.dpAmount > 0 ? 'Terdaftar' : 'Terdaftar'
    };

    // Calculate price
    const pkg = packages.find(p => p.id === jamaahData.packageId);
    const tier = pkg?.tiers.find(t => t.type === bookingDetails.roomType) || pkg?.tiers[0];
    const totalPrice = tier ? tier.priceIdr : 30000000;
    const paidAmount = bookingDetails.dpAmount || 0;
    const remainingAmount = Math.max(0, totalPrice - paidAmount);

    const newBooking: Booking = {
      id: `bk-${Date.now().toString(36)}`,
      bookingCode,
      tenantId: currentTenant.id,
      packageId: jamaahData.packageId,
      jamaahId: newJamId,
      roomType: bookingDetails.roomType,
      totalPrice,
      paidAmount,
      remainingAmount,
      bookingDate: new Date().toISOString().split('T')[0],
      status: paidAmount >= totalPrice ? 'Lunas' : paidAmount > 0 ? 'DP Dibayar' : 'Pending DP',
      payments: []
    };

    setJamaahList(prev => [newJamaah, ...prev]);
    setBookings(prev => [newBooking, ...prev]);

    // Update package booked seat count
    setPackages(prev => prev.map(p => {
      if (p.id === jamaahData.packageId) {
        return { ...p, bookedSeats: p.bookedSeats + 1 };
      }
      return p;
    }));

    // Update tenant jamaah count
    setTenants(prev => prev.map(t => {
      if (t.id === currentTenant.id) {
        return { ...t, currentJamaahCount: t.currentJamaahCount + 1 };
      }
      return t;
    }));

    // If DP paid, record payment & auto journal
    if (paidAmount > 0) {
      const receiptNo = `KW-${currentTenant.code}-${new Date().toISOString().slice(2, 7).replace('-', '')}-${Math.floor(1000 + Math.random() * 9000)}`;
      const newPay: PaymentRecord = {
        id: `pay-${Date.now().toString(36)}`,
        tenantId: currentTenant.id,
        bookingCode,
        receiptNumber: receiptNo,
        jamaahName: jamaahData.namaLengkap,
        packageTitle: pkg?.title || 'Paket Umrah',
        amount: paidAmount,
        paymentType: paidAmount >= totalPrice ? 'Pelunasan' : 'DP',
        paymentMethod: bookingDetails.paymentMethod || 'Bank Transfer (BSI)',
        date: new Date().toISOString().replace('T', ' ').slice(0, 16),
        status: 'Verified',
        receivedBy: 'System Auto-Register'
      };
      setPayments(prev => [newPay, ...prev]);

      // Auto-Journaling into SAK ETAP
      const newJournal: JournalEntry = {
        id: `jrn-${Date.now().toString(36)}`,
        tenantId: currentTenant.id,
        referenceNo: `JV-${currentTenant.code}-${Date.now().toString().slice(-6)}`,
        date: new Date().toISOString().split('T')[0],
        description: `Penerimaan ${newPay.paymentType} ${jamaahData.namaLengkap} (${receiptNo})`,
        kloterCode: pkg?.kloterCode,
        isAutoGenerated: true,
        lines: [
          { accountCode: '1-1110', accountName: 'BSI Giro Operasional', debit: paidAmount, credit: 0 },
          { accountCode: '2-1200', accountName: 'Pendapatan Diterima Dimuka (DP Jamaah)', debit: 0, credit: paidAmount }
        ]
      };
      setJournals(prev => [newJournal, ...prev]);
    }
  };

  const updateJamaahDocStatus = (jamaahId: string, docKey: keyof Jamaah['documents'], status: any) => {
    setJamaahList(prev => prev.map(j => {
      if (j.id === jamaahId) {
        const updatedDocs = { ...j.documents, [docKey]: status };
        const allValid = updatedDocs.ktp === 'Valid' && updatedDocs.paspor === 'Valid' && (updatedDocs.bukuNikah === 'Valid' || updatedDocs.bukuNikah === 'Tidak Perlu');
        const visaIssued = updatedDocs.visa === 'Issued';
        
        let newStatus = j.status;
        if (visaIssued) newStatus = 'Visa Terbit';
        else if (allValid) newStatus = 'Dokumen Siap';

        return { ...j, documents: updatedDocs, status: newStatus };
      }
      return j;
    }));
  };

  const addPayment = (paymentData: Omit<PaymentRecord, 'id' | 'tenantId' | 'receiptNumber'>) => {
    const receiptNumber = `KW-${currentTenant.code}-${new Date().toISOString().slice(2, 7).replace('-', '')}-${Math.floor(1000 + Math.random() * 9000)}`;
    const newPayment: PaymentRecord = {
      ...paymentData,
      id: `pay-${Date.now().toString(36)}`,
      tenantId: currentTenant.id,
      receiptNumber
    };

    setPayments(prev => [newPayment, ...prev]);

    // Update corresponding booking
    setBookings(prev => prev.map(b => {
      if (b.bookingCode === paymentData.bookingCode) {
        const newPaid = b.paidAmount + paymentData.amount;
        const newRemaining = Math.max(0, b.totalPrice - newPaid);
        const newStatus = newRemaining === 0 ? 'Lunas' : newPaid > 0 ? 'Angsuran Sebagian' : b.status;
        return {
          ...b,
          paidAmount: newPaid,
          remainingAmount: newRemaining,
          status: newStatus
        };
      }
      return b;
    }));

    // Auto journal
    const newJournal: JournalEntry = {
      id: `jrn-${Date.now().toString(36)}`,
      tenantId: currentTenant.id,
      referenceNo: `JV-${currentTenant.code}-${Date.now().toString().slice(-6)}`,
      date: new Date().toISOString().split('T')[0],
      description: `Pembayaran ${paymentData.paymentType} Jamaah ${paymentData.jamaahName} (${receiptNumber})`,
      isAutoGenerated: true,
      lines: [
        { accountCode: '1-1110', accountName: 'BSI Giro Operasional', debit: paymentData.amount, credit: 0 },
        { 
          accountCode: paymentData.paymentType === 'Pelunasan' ? '4-1000' : '2-1200', 
          accountName: paymentData.paymentType === 'Pelunasan' ? 'Pendapatan Paket Umrah' : 'Pendapatan Diterima Dimuka (DP Jamaah)', 
          debit: 0, 
          credit: paymentData.amount 
        }
      ]
    };
    setJournals(prev => [newJournal, ...prev]);
  };

  const addJournalEntry = (entry: Omit<JournalEntry, 'id' | 'tenantId' | 'referenceNo' | 'isAutoGenerated'>) => {
    const newEntry: JournalEntry = {
      ...entry,
      id: `jrn-${Date.now().toString(36)}`,
      tenantId: currentTenant.id,
      referenceNo: `JV-MAN-${Date.now().toString().slice(-6)}`,
      isAutoGenerated: false
    };
    setJournals(prev => [newEntry, ...prev]);
  };

  const updateInventoryStock = (itemId: string, warehouse: 'stockPusat' | 'stockBandara' | 'stockCabang', delta: number) => {
    setInventory(prev => prev.map(item => {
      if (item.id === itemId) {
        return {
          ...item,
          [warehouse]: Math.max(0, item[warehouse] + delta)
        };
      }
      return item;
    }));
  };

  const addLead = (leadData: Omit<Lead, 'id' | 'tenantId' | 'updatedAt'>) => {
    const newLead: Lead = {
      ...leadData,
      id: `lead-${Date.now().toString(36)}`,
      tenantId: currentTenant.id,
      updatedAt: new Date().toISOString().split('T')[0]
    };
    setLeads(prev => [newLead, ...prev]);
  };

  const updateLeadStage = (leadId: string, newStage: Lead['stage']) => {
    setLeads(prev => prev.map(l => {
      if (l.id === leadId) {
        return { ...l, stage: newStage, updatedAt: new Date().toISOString().split('T')[0] };
      }
      return l;
    }));
  };

  const sendBroadcast = (broadcastData: Omit<BroadcastLog, 'id' | 'tenantId' | 'sentAt' | 'status'>) => {
    const newBc: BroadcastLog = {
      ...broadcastData,
      id: `bc-${Date.now().toString(36)}`,
      tenantId: currentTenant.id,
      sentAt: new Date().toISOString().replace('T', ' ').slice(0, 16),
      status: 'Delivered'
    };
    setBroadcasts(prev => [newBc, ...prev]);
  };

  const payoutAgentCommission = (agentId: string, amount: number) => {
    setAgents(prev => prev.map(a => {
      if (a.id === agentId) {
        const pay = Math.min(amount, a.pendingCommission);
        return {
          ...a,
          paidCommission: a.paidCommission + pay,
          pendingCommission: Math.max(0, a.pendingCommission - pay)
        };
      }
      return a;
    }));
  };

  return (
    <AppContext.Provider
      value={{
        tenants,
        currentTenant,
        setCurrentTenantId,
        currentUserRole,
        setCurrentUserRole,
        currentView,
        setCurrentView,
        createTenant,
        updateTenantBranding,
        toggleTenantModule,
        packages: packages.filter(p => p.tenantId === currentTenant.id),
        jamaahList: jamaahList.filter(j => j.tenantId === currentTenant.id),
        bookings: bookings.filter(b => b.tenantId === currentTenant.id),
        payments: payments.filter(p => p.tenantId === currentTenant.id),
        coaList,
        journals: journals.filter(j => j.tenantId === currentTenant.id),
        inventory: inventory.filter(i => i.tenantId === currentTenant.id),
        leads: leads.filter(l => l.tenantId === currentTenant.id),
        broadcasts: broadcasts.filter(b => b.tenantId === currentTenant.id),
        agents: agents.filter(a => a.tenantId === currentTenant.id),
        addPackage,
        addJamaah,
        updateJamaahDocStatus,
        addPayment,
        addJournalEntry,
        updateInventoryStock,
        addLead,
        updateLeadStage,
        sendBroadcast,
        payoutAgentCommission,
        theme,
        setTheme,
        toggleTheme,
        formatIdr
      }}
    >
      {children}
    </AppContext.Provider>
  );
};

export const useApp = () => {
  const context = useContext(AppContext);
  if (!context) {
    throw new Error('useApp must be used within an AppProvider');
  }
  return context;
};
